#!/usr/bin/env python3
"""Vendor a fixed-cell X11 bitmap font as a C header for the BIOS console.

    python3 fw/mkfont.py /usr/share/fonts/X11/misc/6x10.pcf.gz > fw/font6x10.h

The output is `static const unsigned char font6x10[128][10]`: one byte per pixel row, bit
(W-1) the leftmost pixel, bit 0 the rightmost (characters 0..31 and 127 are blank). The
cell size comes from the file name (WxH). Needs Pillow for its PCF reader; the font
itself is drawn with Pillow so the glyph sits where X11 would put it (ascent/descent
from the font's metrics)."""
import gzip, io, os, re, sys
from PIL import Image, ImageDraw, ImageFont, PcfFontFile

def main():
    path = sys.argv[1]
    name = os.path.basename(path).split('.')[0]
    w, h = map(int, re.match(r'(\d+)x(\d+)', name).groups())
    raw = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
    pcf = PcfFontFile.PcfFontFile(io.BytesIO(raw))
    tmp = f'/tmp/mkfont_{os.getpid()}_{name}'
    pcf.save(tmp)
    font = ImageFont.load(tmp + '.pil')
    for ext in ('.pil', '.pbm'):
        os.unlink(tmp + ext)
    out = sys.stdout
    out.write(f'/* {name}: generated by fw/mkfont.py from {os.path.basename(path)} (the X11 misc-fixed\n'
              f' * font "{name}", public domain). Do not edit; rerun the script.\n'
              f' * One byte per pixel row, bit {w - 1} is the leftmost pixel, bit 0 the rightmost.\n'
              f' * Characters 0..31 and 127 are blank. */\n'
              f'#define FONT{w}X{h}_W {w}\n#define FONT{w}X{h}_H {h}\n'
              f'static const unsigned char font{w}x{h}[128][{h}] = {{\n')
    for c in range(128):
        rows = [0] * h
        if 32 <= c < 127:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
            px = im.load()
            for y in range(h):
                for x in range(w):
                    if px[x, y]:
                        rows[y] |= 1 << (w - 1 - x)
        label = f'U+{c:04X}' + (f' {chr(c)!r}' if 32 <= c < 127 else '')
        out.write('    { ' + ', '.join(f'0x{r:02X}' for r in rows) + ' },   /* ' + label.replace('*/', '* /') + ' */\n')
    out.write('};\n')

main()
